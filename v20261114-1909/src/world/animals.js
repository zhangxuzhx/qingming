// 牲畜：驴、马、牛、骆驼。身、颈、头、腿都是沿脊线放样的软管，
// 背深腹浅（画里的牲口多是背上一层重染、腹下留淡），鬃、尾、蹄用浓墨色。全部朝 +X。
const F = 'fig';
const SIDE = [0, 0, 1];
const CORD = [0.4, 0.36, 0.3], WOODC = [0.62, 0.5, 0.38];

// pts: [x, y, 半宽, 半高]（居中于 z=0）或 [x, y, z, ra, rb]
const tube = (b, pts, color, id, o) => b.tube(F, pts.map((p) => (p.length === 4 ? [p[0], p[1], 0, p[2], p[3]] : p)), { color, id, side: SIDE, seg: 10, ...o });
const ball = (b, x, y, z, rx, ry, rz, color, id, o) => b.sphere(F, x, y, z, rx, ry, rz, { color, id, ...o });
const rod = (b, a, c, r0, r1, color, id, lw = 0.5) => b.rod(F, a, c, r0, r1, 5, { color, id, lw });

// 前腿：肩 → 膝 → 球节 → 蹄
function foreleg(b, x, top, z, st, L, col, dark, id) {
  const r = L.r, kn = L.knee;
  tube(b, [[x, top, z, r * 1.5, r * 2.0], [x + 0.02 + st * 0.25, top - (top - kn) * 0.55, z, r * 1.15, r * 1.3], [x + 0.03 + st * 0.5, kn, z, r * 1.1, r * 1.14], [x + 0.012 + st * 0.76, kn * 0.5, z, r * 0.78, r * 0.8], [x + st, L.hoof + 0.04, z, r * 0.84, r * 0.92]], col, id, { seg: 7, capA: false });
  foot(b, x + st, z, L, dark, id);
}
// 后腿：髋 → 膝 → 飞节（向后折）→ 球节 → 蹄
function hindleg(b, x, top, z, st, L, col, dark, id) {
  const r = L.r, hk = L.hock;
  tube(b, [[x, top, z, r * 1.9, r * 2.7], [x + 0.07 + st * 0.2, (top + hk) / 2 + 0.03, z, r * 1.45, r * 1.85], [x - 0.075 + st * 0.5, hk, z, r * 1.0, r * 1.12], [x - 0.03 + st * 0.8, hk * 0.45, z, r * 0.78, r * 0.8], [x + st, L.hoof + 0.04, z, r * 0.84, r * 0.92]], col, id, { seg: 7, capA: false });
  foot(b, x + st, z, L, dark, id);
}
function foot(b, x, z, L, dark, id) {
  const r = L.r;
  if (L.pad) ball(b, x + 0.03, 0.045, z, L.pad * 1.15, 0.05, L.pad, L.padCol || dark, id, { ws: 8, hs: 5, lw: 0.6 });
  else tube(b, [[x, L.hoof + 0.055, z, r * 0.95, r * 1.05], [x + 0.014, 0, z, r * 1.2, r * 1.38]], dark, id, { seg: 7 });
}
function legs(b, S, col, dark, id, gait) {
  const g = gait ?? 0.1;
  for (const sz of [-1, 1]) {
    foreleg(b, S.fx, S.ftop, sz * S.fz, sz * g, S.leg, col, dark, id);
    hindleg(b, S.hx, S.htop, sz * S.hz, -sz * g, S.leg, col, dark, id);
  }
}
function eyes(b, x, y, z, id) {
  for (const sz of [-1, 1]) ball(b, x, y, sz * z, 0.016, 0.016, 0.012, [0.16, 0.15, 0.15], id, { ws: 5, hs: 4, lw: 0.3 });
}

